pub enum ErrorCode {
    Unauthorized,
    Forbidden,
    InternalError,
    MissingApiKey,
    InvalidApiKey,
    ApiKeyDisabled,
    ApiKeyExpired,
    CrossRealmAccessForbidden,
    InvalidUserIdFormat,
    MissingUserId,
    InvalidClientAppIdFormat,
    InvalidAmount,
    InsufficientPoints,
    WalletFrozenOrClosed,
    InvalidTransactionIdFormat,
    IdempotencyConflict,
    ConcurrentModification,
    RateLimitExceeded,
    WalletNotFound,
    TransactionNotFound,
    ClientAppNotFound,
    SubscriptionNotFound,
    PermissionDenied,
    RealmNotFound,
    UserNotFound,
    EmailAlreadyExists,
    PlatformPermissionRequired,
    ValidationError,
    ClientAppDisabled,
    OrgNotFound,
    OrgOwnerProtected,
    OrgLastAdminProtected,
    OrgRoleNotFound,
    OrgMemberNotFound,
    OrgAccountScopeMismatch,
    OrgActorNotManager,
    OrgActorSelfHoldRequired,
    OrgOwnershipTransferDenied,
    OrgClientAppKeyRequired,
}

